const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const ctx=vm.createContext({});
vm.runInContext(fs.readFileSync(require('node:path').join(__dirname,'../lib/js/utilidades.js'),'utf8'),ctx);
const anterior=[{uid:'combo-1',id:'28',nombre:'Combo',precioBase:4990,cant:1,combo:null,extras:[{id:'agua',nombre:'Agua Mineral',precio:1200}]}];
const filas=ctx.separarExtrasCarrito(anterior,()=>({img:'agua.jpg'}));
const total=()=>filas.reduce((s,l)=>s+l.precioBase*l.cant,0);
assert.equal(filas.length,2);
assert.equal(filas[0].extras.length,0);
assert.equal(filas[1].nombre,'Agua Mineral');
assert.equal(filas[1].tipo_linea,'extra');
assert.equal(total(),6190,'migración no cambia el importe');
filas[1].cant++;
assert.equal(total(),7390,'aumentar agua no aumenta el combo');
assert.equal(filas[0].cant,1);
filas.splice(1,1);
assert.equal(total(),4990,'eliminar agua conserva el combo');
assert.equal(anterior[0].extras.length,1,'no modifica el modelo anterior');
const doble=ctx.separarExtrasCarrito([{...anterior[0],cant:2}],()=>({}));
assert.equal(doble[1].cant,2,'conserva cantidades de carritos anteriores');
assert.equal(ctx.separarExtrasCarrito(doble,()=>({})).length,2,'migración idempotente');
console.log('OK: extras independientes, cantidades, eliminación y migración sin duplicar importes.');
vm.runInContext(fs.readFileSync(require('node:path').join(__dirname,'../lib/js/ventas.js'),'utf8'),ctx);
const plano=ctx.separarExtrasCarrito(anterior,()=>({}));
const venta=ctx.prepararVenta({tipoOrden:'Para llevar',metodoPago:'efectivo',descuento:0,carrito:plano},
    {cliente:1,sucursal:2,centro:1},null,()=>null,p=>p,new Date(),'test-extra-independiente-0001');
assert.equal(venta.detalle.length,2);
assert.equal(venta.detalle[1].tipo,'extra');
assert.equal(venta.totales.total,6190,'journal sin duplicar el extra separado');
assert.equal(venta.totales.unidades,2);
